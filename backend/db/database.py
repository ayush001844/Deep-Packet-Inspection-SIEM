"""
Database – Async SQLite persistence via SQLAlchemy 2.0
======================================================
Stores packets, alerts, incidents, and threat intel cache.
"""

from __future__ import annotations

import os
from datetime import datetime
from typing import Any, Optional

from sqlalchemy import (
    Column, Integer, String, Float, Text, Boolean, DateTime,
    JSON, create_engine, event,
)
from sqlalchemy.orm import declarative_base, sessionmaker, Session

# ---------------------------------------------------------------------------
# Setup
# ---------------------------------------------------------------------------

DB_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "data")
os.makedirs(DB_DIR, exist_ok=True)
# Default to PostgreSQL, fallback to SQLite for backward compatibility if needed
DATABASE_URL = os.getenv("DATABASE_URL", "postgresql://postgres:postgres@localhost:5432/soc")


engine = create_engine(DATABASE_URL, echo=False, future=True)
SessionLocal = sessionmaker(bind=engine, expire_on_commit=False)
Base = declarative_base()

# SQLite WAL pragmas only applied if using sqlite
@event.listens_for(engine, "connect")
def _set_sqlite_pragma(dbapi_connection, connection_record):
    if "sqlite" in DATABASE_URL:
        cursor = dbapi_connection.cursor()
        cursor.execute("PRAGMA journal_mode=WAL")
        cursor.execute("PRAGMA synchronous=NORMAL")
        cursor.close()


# ---------------------------------------------------------------------------
# Models
# ---------------------------------------------------------------------------

class PacketRecord(Base):
    """Persisted packet summary (not every packet – only flagged / sampled)."""
    __tablename__ = "packets"

    id = Column(Integer, primary_key=True, autoincrement=True)
    timestamp = Column(Float, index=True)
    src_ip = Column(String(45), index=True)
    dst_ip = Column(String(45), index=True)
    src_port = Column(Integer)
    dst_port = Column(Integer)
    protocol = Column(String(16), index=True)
    length = Column(Integer)
    summary = Column(Text)
    layers_json = Column(JSON)  # Full layer data as JSON
    created_at = Column(DateTime, default=datetime.utcnow)


class Alert(Base):
    """Security alert generated by IDS / IOC / Sigma / YARA."""
    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True, autoincrement=True)
    timestamp = Column(Float, index=True)
    severity = Column(String(16), index=True)  # critical, high, medium, low, info
    classification = Column(String(128))       # Real-time attack classification
    title = Column(String(256))
    description = Column(Text)
    source = Column(String(32))  # ids, ioc, sigma, yara
    mitre_technique = Column(String(32))   # e.g. T1110
    mitre_tactic = Column(String(64))      # e.g. Credential Access
    src_ip = Column(String(45))
    dst_ip = Column(String(45))
    protocol = Column(String(16))
    cvss_score = Column(Float)
    cvss_vector = Column(String(128))
    raw_data = Column(JSON)
    is_acknowledged = Column(Boolean, default=False)
    incident_id = Column(Integer, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)


class Incident(Base):
    """SIEM incident (aggregates related alerts)."""
    __tablename__ = "incidents"

    id = Column(Integer, primary_key=True, autoincrement=True)
    incident_id = Column(String(16), unique=True, index=True)  # INC-0001
    title = Column(String(256))
    description = Column(Text)
    severity = Column(String(16))  # critical, high, medium, low
    status = Column(String(32), default="new")  # new, investigating, contained, resolved
    priority = Column(Integer, default=3)  # 1 = highest
    assigned_to = Column(String(64))
    alert_ids = Column(JSON, default=list)
    notes = Column(JSON, default=list)  # [{timestamp, author, text}]
    evidence = Column(JSON, default=list)
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    resolved_at = Column(DateTime, nullable=True)


class User(Base):
    """Application user with role-based access."""
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, autoincrement=True)
    username = Column(String(64), unique=True, index=True, nullable=False)
    hashed_password = Column(String(256), nullable=False)
    role = Column(String(16), default="analyst")  # admin | analyst
    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime, default=datetime.utcnow)


class ThreatIntelCache(Base):
    """Cache for external threat intelligence lookups."""
    __tablename__ = "threat_intel_cache"

    id = Column(Integer, primary_key=True, autoincrement=True)
    indicator = Column(String(256), unique=True, index=True)  # IP, domain, hash
    indicator_type = Column(String(16))  # ip, domain, hash, url
    results = Column(JSON)  # Cached API results
    risk_score = Column(Float)
    is_malicious = Column(Boolean, default=False)
    created_at = Column(DateTime, default=datetime.utcnow)
    expires_at = Column(DateTime)  # Cache TTL


class IOCEntry(Base):
    """Indicator of Compromise entry."""
    __tablename__ = "ioc_entries"

    id = Column(Integer, primary_key=True, autoincrement=True)
    indicator = Column(String(256), index=True)
    indicator_type = Column(String(16))  # ip, domain, hash, url, email
    source = Column(String(64))  # manual, feed, virustotal
    description = Column(Text)
    is_active = Column(Boolean, default=True)
    match_count = Column(Integer, default=0)
    last_matched = Column(DateTime, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)


# ---------------------------------------------------------------------------
# Database operations
# ---------------------------------------------------------------------------

def init_db() -> None:
    """Create all tables."""
    Base.metadata.create_all(engine)


def get_session() -> Session:
    """Get a new database session."""
    return SessionLocal()


def save_alert(
    title: str,
    description: str,
    severity: str = "medium",
    source: str = "ids",
    mitre_technique: str = "",
    mitre_tactic: str = "",
    classification: str = "",
    src_ip: str = "",
    dst_ip: str = "",
    cvss_score: float = 0.0,
    cvss_vector: str = "",
    raw_data: Optional[dict] = None,
) -> int:
    """Save an alert and return its ID."""
    import time as _time
    session = get_session()
    try:
        alert = Alert(
            timestamp=_time.time(),
            severity=severity,
            title=title,
            description=description,
            classification=classification,
            source=source,
            mitre_technique=mitre_technique,
            mitre_tactic=mitre_tactic,
            src_ip=src_ip,
            dst_ip=dst_ip,
            cvss_score=cvss_score,
            cvss_vector=cvss_vector,
            raw_data=raw_data or {},
        )
        session.add(alert)
        session.commit()
        return alert.id
    finally:
        session.close()


def get_alerts(limit: int = 100, severity: Optional[str] = None) -> list[dict[str, Any]]:
    """Retrieve recent alerts."""
    session = get_session()
    try:
        query = session.query(Alert).order_by(Alert.created_at.desc())
        if severity:
            query = query.filter(Alert.severity == severity)
        alerts = query.limit(limit).all()
        result = []
        for a in alerts:
            result.append({
                "id": a.id,
                "timestamp": a.timestamp,
                "severity": a.severity,
                "classification": a.classification,
                "title": a.title,
                "description": a.description,
                "source": a.source,
                "mitre_technique": a.mitre_technique,
                "mitre_tactic": a.mitre_tactic,
                "src_ip": a.src_ip,
                "dst_ip": a.dst_ip,
                "cvss_score": a.cvss_score,
                "is_acknowledged": a.is_acknowledged,
                "incident_id": a.incident_id,
                "created_at": a.created_at.isoformat() if a.created_at else "",
            })
        return result
    finally:
        session.close()


def get_incidents(limit: int = 50) -> list[dict[str, Any]]:
    """Retrieve incidents."""
    session = get_session()
    try:
        incidents = session.query(Incident).order_by(Incident.created_at.desc()).limit(limit).all()
        result = []
        for inc in incidents:
            result.append({
                "id": inc.id,
                "incident_id": inc.incident_id,
                "title": inc.title,
                "description": inc.description,
                "severity": inc.severity,
                "status": inc.status,
                "priority": inc.priority,
                "assigned_to": inc.assigned_to,
                "alert_ids": inc.alert_ids or [],
                "notes": inc.notes or [],
                "evidence": inc.evidence or [],
                "created_at": inc.created_at.isoformat() if inc.created_at else "",
                "updated_at": inc.updated_at.isoformat() if inc.updated_at else "",
            })
        return result
    finally:
        session.close()


# Initialize on import
init_db()
